  assert.match(auto,/progress\."pendingMinor"/);
  assert.match(auto,/ORDER BY e\.id FOR UPDATE OF e/);
  assert.match(auto,/completed_at IS NULL/);
  assert.match(auto,/origin,triggered_by/);
